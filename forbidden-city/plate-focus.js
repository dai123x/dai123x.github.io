export function detailView(area, image, focus) {
  const scale = Math.min(area.width / image.width, area.height / image.height) * focus.zoom;
  return { zoom: focus.zoom, x: (image.width / 2 - focus.x) * scale, y: (image.height / 2 - focus.y) * scale };
}
